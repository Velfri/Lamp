#!/usr/bin/env python3
"""Генерує espcode/web_assets.h із вебфайлів (gzip + C-масиви).

Лампа віддає застосунок просто зі своєї флеш-пам'яті. Файли стискаються gzip,
а WEB_HASH змінюється при кожній зміні вмісту — це ETag для браузера.

Запуск:  python3 tools/gen_web_assets.py
"""
import gzip
import hashlib
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

ASSETS = [
    # (шлях на лампі, файл, MIME)
    ('/apple-touch-icon.png', 'apple-touch-icon.png', 'image/png'),
    ('/icon-192.png', 'icon-192.png', 'image/png'),
    ('/icon-512.png', 'icon-512.png', 'image/png'),
    ('/index.html', 'index.html', 'text/html; charset=utf-8'),
    ('/manifest.json', 'manifest.json', 'application/json; charset=utf-8'),
    ('/service-worker.js', 'service-worker.js', 'application/javascript; charset=utf-8'),
]


def gz(data: bytes) -> bytes:
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode='wb', compresslevel=9, mtime=0) as f:
        f.write(data)
    return buf.getvalue()


def main() -> int:
    out = []
    out.append('// GENERATED by tools/gen_web_assets.py. Do not edit manually.')
    out.append('#pragma once')
    out.append('#include <Arduino.h>')
    out.append('')
    out.append('struct WebAsset { const char* path; const char* mime; const uint8_t* data; uint32_t len; };')
    out.append('')

    entries = []
    h = hashlib.sha256()
    total = 0
    for idx, (path, rel, mime) in enumerate(ASSETS):
        full = os.path.join(ROOT, rel)
        if not os.path.exists(full):
            print(f'! пропущено (немає файлу): {rel}', file=sys.stderr)
            continue
        raw = open(full, 'rb').read()
        packed = gz(raw)
        h.update(path.encode())
        h.update(packed)
        total += len(packed)
        out.append(f'// {path}  ({len(raw)} B -> {len(packed)} B gzip)')
        out.append(f'static const uint8_t asset_{idx}[] PROGMEM = {{')
        line = []
        for i, b in enumerate(packed):
            line.append(f'0x{b:02x},')
            if len(line) == 16:
                out.append('  ' + ' '.join(line))
                line = []
        if line:
            out.append('  ' + ' '.join(line))
        out.append('};')
        out.append('')
        entries.append((path, mime, f'asset_{idx}', len(packed)))

    web_hash = h.hexdigest()[:10]
    out.insert(5, f'#define WEB_HASH "{web_hash}"')
    out.append('static const WebAsset WEB_ASSETS[] = {')
    for path, mime, var, ln in entries:
        out.append(f'  {{"{path}", "{mime}", {var}, {ln}}},')
    out.append('};')
    out.append(f'static const size_t WEB_ASSET_COUNT = {len(entries)};')

    dst = os.path.join(ROOT, 'espcode', 'web_assets.h')
    with open(dst, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print(f'web_assets.h: {len(entries)} файлів, {total / 1024:.1f} КБ gzip, WEB_HASH={web_hash}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
